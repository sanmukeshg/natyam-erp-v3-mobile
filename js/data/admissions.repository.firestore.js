/**
 * NATYAM ERP 2.0 — Admissions repository (Firestore)
 *
 * Milestone 5: the third store to move off IndexedDB (see ADR-014,
 * docs/migrations/ADMISSIONS_MODULE_MIGRATION.md). Keeps the exact external
 * shape the old IndexedDB-backed AdmissionRepository and the base
 * Repository class it extended had — find/findOrFail/all/where/count/
 * search/create/update/save/remove/restore/createMany, plus
 * Admission-specific pending/byStatus/recent/findLikeness/findAllLikeness —
 * so admissions.service.js and every module that calls it needed no changes
 * beyond the one repository-bypass fixed in enrolApplicant() (see the
 * migration doc §4).
 *
 * Field names are unchanged from the IndexedDB model — deliberately not
 * renamed, since admissions.service.js and several read-only callers
 * (reports/dashboard/analytics/notifications/search) depend on these exact
 * names.
 *
 * Document Identifier Standard: the Firestore document id is auto-generated
 * (`addDoc`) and never shown to a user. Unlike Students (which needed a new
 * `studentCode`), Admissions already has a real, human-facing business
 * identifier — `applicationNo` (`NAT/APP/26/0007`-style) — generated by
 * `settings$.nextSequence('application')`, which stays on IndexedDB
 * unchanged (Settings is out of scope for this migration, and the format
 * is a year-scoped sequence, not the flat code `sequenceGenerator.
 * firestore.js` produces). No new business-code field is introduced here.
 * See docs/migrations/ADMISSIONS_MODULE_MIGRATION.md for the full record.
 */

import {
    collection, doc, addDoc, setDoc, updateDoc, deleteDoc, query, where, limit as fsLimit, writeBatch
} from 'https://www.gstatic.com/firebasejs/12.16.0/firebase-firestore.js';
import { firestore } from '../core/firebase.js';
import { session } from '../core/session.js';
import { recordAuditEntry } from './auditLog.repository.firestore.js';
import { nowISO, localDate } from '../utils/date.js';
import { ADMISSION_STATUS } from '../config/app.config.js';
import { getDoc, getDocs } from './firestoreRead.js';

const COLLECTION_NAME = 'admissions';
const admissionsCollection = collection(firestore, COLLECTION_NAME);
const SEARCH_FIELDS = ['name', 'applicationNo', 'guardianName', 'guardianPhone'];

/** Soft-delete convention, same as the IndexedDB Repository base class. */
function visible(record) {
    return record && !record.deletedAt;
}

/** Collapses whitespace and keeps only digits and a leading +. Same rule the old repository used. */
function normalisePhone(value) {
    if (!value) return null;
    const cleaned = String(value).replace(/[^\d+]/g, '');
    return cleaned || null;
}

function searchKeyOf(record) {
    return SEARCH_FIELDS
        .map((f) => record[f])
        .filter((v) => v !== null && v !== undefined && v !== '')
        .join(' ')
        .toLowerCase();
}

async function writeAuditRow(action, id, detail) {
    await recordAuditEntry('Admission', action, id, detail);
}

class FirestoreAdmissionRepository {
    /* ---------------------------------------------------------------- HOOKS */

    beforeSave(record) {
        return {
            ...record,
            name: String(record.name || '').trim().replace(/\s+/g, ' '),
            status: record.status || ADMISSION_STATUS.SUBMITTED,
            guardianPhone: normalisePhone(record.guardianPhone),
            appliedOn: record.appliedOn || localDate()
        };
    }

    validate(record) {
        if (!record.name) throw new Error('The applicant needs a name.');
        if (!record.branchId) throw new Error('Choose the branch being applied to.');
        if (!record.guardianPhone) throw new Error('A parent or guardian contact number is required.');
        if (!record.level) throw new Error('Choose a starting level.');
    }

    /* ---------------------------------------------------------------- READS */

    async find(id) {
        if (!id) return null;
        const snap = await getDoc(doc(firestore, COLLECTION_NAME, id));
        if (!snap.exists()) return null;
        const record = { id: snap.id, ...snap.data() };
        return visible(record) ? record : null;
    }

    async findOrFail(id) {
        if (!id) throw new Error('No admission was specified.');
        const record = await this.find(id);
        if (!record) throw new Error(`Admission ${id} no longer exists.`);
        return record;
    }

    async all({ includeDeleted = false } = {}) {
        const snap = await getDocs(admissionsCollection);
        const rows = snap.docs.map((d) => ({ id: d.id, ...d.data() }));
        return includeDeleted ? rows : rows.filter(visible);
    }

    /** `index` is a plain Firestore field name here — single-field equality needs no pre-declared index. */
    async where(index, value) {
        const snap = await getDocs(query(admissionsCollection, where(index, '==', value)));
        return snap.docs.map((d) => ({ id: d.id, ...d.data() })).filter(visible);
    }

    async count(index, value) {
        if (!index) return (await this.all()).length;
        return (await this.where(index, value)).length;
    }

    /**
     * Prefix search over `searchKey`, same technique as the Students
     * repository — a range query, falling back to a full-collection
     * substring scan only when the prefix range comes up short.
     */
    async search(term, { limit: max = 20 } = {}) {
        const q = String(term || '').trim().toLowerCase();
        if (!q) return [];

        const prefixSnap = await getDocs(query(
            admissionsCollection,
            where('searchKey', '>=', q),
            where('searchKey', '<', `${q}`),
            fsLimit(max)
        ));
        const prefixHits = prefixSnap.docs.map((d) => ({ id: d.id, ...d.data() })).filter(visible);
        if (prefixHits.length >= max) return prefixHits;

        const seen = new Set(prefixHits.map((r) => r.id));
        const rest = (await this.all())
            .filter((r) => !seen.has(r.id) && (r.searchKey || '').includes(q))
            .slice(0, max - prefixHits.length);

        return [...prefixHits, ...rest];
    }

    /* --------------------------------------------------------------- WRITES */

    async create(data) {
        const record = this.beforeSave({ ...data });
        this.validate(record);
        delete record.id;

        const at = nowISO();
        const actor = session.actorId();

        const full = {
            ...record,
            createdAt: at, createdBy: actor,
            updatedAt: at, updatedBy: actor,
            deletedAt: null,
            searchKey: searchKeyOf(record)
        };

        const ref = await addDoc(admissionsCollection, full);
        await writeAuditRow('create', ref.id);
        return { id: ref.id, ...full };
    }

    /**
     * A prospective parent submitting their OWN application (Parent Portal
     * Stage 3). Separate from create() above for two reasons, both hard
     * requirements rather than preferences:
     *
     *  - NO AUDIT ROW. create() awaits writeAuditRow(), which writes to
     *    /auditLog behind `isProvisionedActiveUser()`. An applicant has no
     *    /users document and never satisfies that, so the audit write throws
     *    AFTER addDoc() has already succeeded — the application exists and the
     *    parent is told it failed. The document carries its own
     *    submittedByEmail and createdAt, which is the provenance this row type
     *    needs; the ERP writes a real audit entry when staff first act on it.
     *
     *  - EXPLICIT ATTRIBUTION. session.actorId() returns the string 'system'
     *    with no hydrated session (js/core/session.js), which would file every
     *    parent submission under the app's own internal attribution.
     *
     * The four server-forced values below are mirrored exactly by
     * firestore.rules' isSelfSubmittedApplication(); the two must be edited
     * together, or a legitimate submission fails with a permissions error
     * instead of a field message.
     *
     * @param {object} data   A validated application (admissions.parent.service.js).
     * @param {string} email  The caller's verified Google identity.
     */
    async createSelfSubmitted(data, email) {
        const record = this.beforeSave({ ...data });

        // NOT this.validate(), which requires branchId — and a prospective
        // parent cannot supply one. /branches is staff-gated, and the public
        // Branches page is hand-written Website Content that deliberately
        // carries no branch ids (decoupling those was an explicit decision).
        // So the parent names the branch they want as free text
        // (`preferredBranch`) and Reception attaches the real branchId when
        // they review, exactly as they allocate the NAT/APP number. A parent
        // supplies intent; staff supply the ERP linkage.
        if (!record.name) throw new Error('The applicant needs a name.');
        if (!record.guardianPhone) throw new Error('A parent or guardian contact number is required.');
        if (!record.level) throw new Error('Choose a starting level.');

        delete record.id;

        const at = nowISO();

        const full = {
            ...record,
            // Server-forced, and matched by the rules. `applicationNo` stays
            // null until the Desktop ERP allocates NAT/APP from the
            // staff-gated sequence when Reception begins review.
            applicationNo: null,
            status: ADMISSION_STATUS.SUBMITTED,
            source: 'parent_portal',
            submittedByEmail: email,

            createdAt: at, createdBy: email,
            updatedAt: at, updatedBy: email,
            deletedAt: null,
            searchKey: searchKeyOf(record)
        };

        const ref = await addDoc(admissionsCollection, full);
        return { id: ref.id, ...full };
    }

    /**
     * Every application one identity has submitted, newest first.
     *
     * A single-field equality query on exactly the field firestore.rules'
     * isMyOwnApplication() compares — the same shape the guardian rules on
     * /students already rely on, so it is servable without opening the
     * collection to the caller.
     */
    async mine(email) {
        if (!email) return [];

        // BOTH filters are required, and the `source` one is not redundant.
        //
        // firestore.rules' isMyOwnApplication() tests two things on the
        // document: `source == 'parent_portal'` AND `submittedByEmail ==
        // myEmail()`. For a LIST query Firestore does not evaluate the rule
        // per document — it requires the query itself to be provably confined
        // to documents the rule allows. A query filtering on only one of the
        // two conditions cannot be proven safe, so Firestore rejects the whole
        // query with permission-denied even when every document it would have
        // returned was readable.
        //
        // That is exactly what broke the My Applications screen: the read
        // failed outright and the page showed its "could not load" state. The
        // query and the rule have to name the same fields; if either changes,
        // the other must too.
        const snap = await getDocs(query(
            admissionsCollection,
            where('source', '==', 'parent_portal'),
            where('submittedByEmail', '==', email)
        ));
        return snap.docs
            .map((d) => ({ id: d.id, ...d.data() }))
            .filter(visible)
            .sort((a, b) => String(b.createdAt || '').localeCompare(String(a.createdAt || '')));
    }

    /**
     * MIGRATION USE ONLY — not called by any normal application code path.
     * Writes a Firestore document from a legacy IndexedDB record while
     * preserving its original audit metadata and `applicationNo`, rather
     * than re-stamping them the way create() does for a genuinely new
     * record. Always creates a new document (a Firestore auto-generated
     * id) — it never reuses the source record's old IndexedDB id. Does not
     * write its own audit row; the migration orchestrator writes one
     * summary row for the whole run instead of one per record.
     *
     * @param {object} record  A full IndexedDB-shaped admission record.
     * @returns {Promise<object>} the new Firestore record, with its id.
     */
    async importLegacyRecord(record) {
        const prepared = this.beforeSave({ ...record });
        this.validate(prepared);

        // Preserve a backup/restore record's real id — other collections
        // (students created from an enrolled application, notifications,
        // …) may reference it. A genuine 1.0-migration record has no `id`
        // at all, so that path is unaffected and still mints a fresh one.
        const explicitId = prepared.id || null;
        delete prepared.id;

        const now = nowISO();
        const full = {
            ...prepared,
            createdAt: record.createdAt || now,
            createdBy: record.createdBy || 'migration',
            updatedAt: record.updatedAt || now,
            updatedBy: record.updatedBy || 'migration',
            deletedAt: record.deletedAt || null,
            deletedBy: record.deletedBy || null,
            searchKey: searchKeyOf(prepared)
        };

        if (explicitId) {
            await setDoc(doc(admissionsCollection, explicitId), full);
            return { id: explicitId, ...full };
        }

        const ref = await addDoc(admissionsCollection, full);
        return { id: ref.id, ...full };
    }

    /**
     * RESTORE USE ONLY (js/services/backup.service.js). Deletes every
     * existing admission document, then imports `records` (each preserving
     * its original metadata via importLegacyRecord(), same as the data
     * migration utility) — "replace", not "merge", matching restore()'s
     * existing all-or-nothing semantics for every other store.
     *
     * @param {object[]} records
     * @returns {Promise<number>} how many were imported
     */
    async replaceAll(records) {
        const existing = await this.all({ includeDeleted: true });

        // Firestore batches cap at 500 operations; chunk defensively even
        // though this school's scale is far below that today.
        for (let i = 0; i < existing.length; i += 450) {
            const chunk = existing.slice(i, i + 450);
            const batch = writeBatch(firestore);
            for (const row of chunk) batch.delete(doc(firestore, COLLECTION_NAME, row.id));
            await batch.commit();
        }

        let imported = 0;
        for (const record of records) {
            await this.importLegacyRecord(record);
            imported += 1;
        }
        return imported;
    }

    /** Full-record replace via updateDoc, matching the IndexedDB version's put()-based semantics. */
    async update(id, changes) {
        const existing = await this.findOrFail(id);
        const merged = this.beforeSave({ ...existing, ...changes, id });
        this.validate(merged);

        merged.updatedAt = nowISO();
        merged.updatedBy = session.actorId();
        merged.searchKey = searchKeyOf(merged);
        delete merged.id;
        delete merged.createdAt;
        delete merged.createdBy;

        await updateDoc(doc(firestore, COLLECTION_NAME, id), merged);

        // Record what actually changed, not the whole object.
        const changed = Object.keys(changes).filter((k) => existing[k] !== merged[k]);
        await writeAuditRow('update', id, { fields: changed });

        return { ...existing, ...merged, id };
    }

    /** Insert or update depending on whether the id already exists. */
    async save(data) {
        if (data.id && await this.find(data.id)) return this.update(data.id, data);
        return this.create(data);
    }

    /** Soft delete by default — an admission is part of a family's record. Hard delete issues a real Firestore delete. */
    async remove(id, { hard = false } = {}) {
        if (hard) {
            await deleteDoc(doc(firestore, COLLECTION_NAME, id));
            await writeAuditRow('delete', id, { hard: true });
            return true;
        }
        await this.findOrFail(id);
        await updateDoc(doc(firestore, COLLECTION_NAME, id), {
            deletedAt: nowISO(),
            deletedBy: session.actorId()
        });
        await writeAuditRow('archive', id);
        return true;
    }

    async restore(id) {
        const snap = await getDoc(doc(firestore, COLLECTION_NAME, id));
        if (!snap.exists()) throw new Error(`Admission ${id} no longer exists.`);
        await updateDoc(doc(firestore, COLLECTION_NAME, id), {
            deletedAt: null,
            deletedBy: null,
            updatedAt: nowISO()
        });
        await writeAuditRow('restore', id);
        return true;
    }

    /** Bulk create via one atomic batch write. */
    async createMany(items) {
        const batch = writeBatch(firestore);
        const at = nowISO();
        const actor = session.actorId();
        const records = [];

        for (const item of items) {
            const record = this.beforeSave({ ...item });
            this.validate(record);
            delete record.id;

            const full = {
                ...record,
                createdAt: at, createdBy: actor,
                updatedAt: at, updatedBy: actor,
                deletedAt: null,
                searchKey: searchKeyOf(record)
            };
            const ref = doc(admissionsCollection);
            batch.set(ref, full);
            records.push({ id: ref.id, ...full });
        }

        await batch.commit();
        await writeAuditRow('createMany', null, { count: records.length });
        return records;
    }

    /* ------------------------------------------------------- ADMISSION QUERIES */

    async pending() {
        const rows = await this.all();
        return rows.filter((a) => [ADMISSION_STATUS.SUBMITTED, ADMISSION_STATUS.REVIEWING].includes(a.status));
    }

    async byStatus(status) {
        return this.where('status', status);
    }

    async recent(limit = 5) {
        return (await this.all())
            .sort((a, b) => (b.appliedOn || '').localeCompare(a.appliedOn || ''))
            .slice(0, limit);
    }

    /** Duplicate guard: same name and guardian phone, still in the pipeline. */
    async findLikeness({ name, guardianPhone }) {
        const phone = normalisePhone(guardianPhone);
        if (!phone) return null;
        const rows = await this.all();
        return rows.find((a) =>
            a.status !== ADMISSION_STATUS.REJECTED &&
            a.guardianPhone === phone &&
            a.name.toLowerCase() === String(name || '').trim().toLowerCase()
        ) || null;
    }

    /** Same match as findLikeness, but returns every other application that matches (self excluded) — for display, not a submit-time guard. */
    async findAllLikeness({ id, name, guardianPhone }) {
        const phone = normalisePhone(guardianPhone);
        if (!phone) return [];
        const rows = await this.all();
        return rows.filter((a) =>
            a.id !== id &&
            a.status !== ADMISSION_STATUS.REJECTED &&
            a.guardianPhone === phone &&
            a.name.toLowerCase() === String(name || '').trim().toLowerCase()
        );
    }
}

export const admissions$ = new FirestoreAdmissionRepository();
